class Client:
    def __init__(self, server, protocol, socket_or_addr, def_channel):
        self.server = server
        self.protocol = protocol
        self.active = True
        self.channel = def_channel
        self.binary_mode = False
        self.last_msg_id = 0
        self.display_name = None

        if protocol == "tcp":
            self.skt = socket_or_addr
            self.addr = socket_or_addr.getpeername()
            self.thread = threading.Thread(target=self.handle_tcp)
            self.thread.start()
        else:
            self.skt = None
            self.addr = socket_or_addr

    def send_udp_binary_message(self, client, msg_type_byte, msg_id, payload=b''):
        if not client.active or client.protocol != "udp":
            return False

        protocol_type = "UDP"

        if msg_type_byte == MSG_TYPE_PING:
            print(f"SEND ({protocol_type}, '{client.addr[0]}', {client.addr[1]}): PING {msg_id} {msg_id:04X}")

        binary_msg = struct.pack('!BH', msg_type_byte, msg_id) + payload

        try:
            if msg_type_byte != MSG_TYPE_CONFIRM:
                self.track_udp_message(client.addr, msg_id, msg_type_byte)

            self.udp_socket.sendto(binary_msg, client.addr)
            return True
        except Exception as e:
            print(f"Error sending UDP message: {e}")
            return False

    def handle_tcp(self):
        try:
            while self.active:
                data = self.skt.recv(60200)
                if not data:
                    break

                self.server.handle_msg(self, data.decode('ascii'))
        except Exception as e:
            print(f"Error handling TCP client: {e}")
        finally:
            self.close()

    def close(self):
        if not self.active:
            return
        self.active = False

        if self.protocol == "tcp" and self.skt:
            try:
                self.skt.shutdown(socket.SHUT_RDWR)
                self.skt.close()
            except:
                pass

        if self in self.server.clients:
            self.server.clients.remove(self)

        if self.protocol == "udp" and self.addr in self.server.udp_clients:
            del self.server.udp_clients[self.addr]

    def send_reply(self, status: bool, message: str):
        protocol_type = "UDP" if self.protocol == "udp" else "TCP"
        s_msg = "OK" if status else "NOK"
        print(f"SEND ({protocol_type}, '{self.addr[0]}', {self.addr[1]}): REPLY {s_msg} IS {message}")

        if self.binary_mode and self.protocol == "udp":
            msg_id = self.server.get_next_msg_id()
            result_byte = 1 if status else 0

            payload = struct.pack('!B', result_byte) + \
                      struct.pack('!H', self.last_msg_id) + \
                      message.encode('utf-8') + b'\x00'

            self.server.send_udp_binary_message(self, MSG_TYPE_REPLY, msg_id, payload)
        else:
            msg = f"REPLY {s_msg} IS {message}\r\n".encode()
            try:
                if self.protocol == "tcp":
                    self.skt.send(msg)
                else:
                    self.server.udp_socket.sendto(msg, self.addr)
            except Exception as e:
                print(f"Error sending reply: {e}")
                self.close()

    def send_bye(self, display_name: str = "Server"):
        if not self.active:
            return

        protocol_type = "UDP" if self.protocol == "udp" else "TCP"
        print(f"SEND ({protocol_type}, '{self.addr[0]}', {self.addr[1]}): BYE FROM {display_name}")

        if self.binary_mode and self.protocol == "udp":
            msg_id = self.server.get_next_msg_id()
            payload = display_name.encode('utf-8') + b'\x00'
            self.server.send_udp_binary_message(self, MSG_TYPE_BYE, msg_id, payload)
        else:
            msg = f"BYE FROM {display_name}\r\n".encode()
            try:
                if self.protocol == "tcp":
                    self.skt.send(msg)
                else:
                    self.server.udp_socket.sendto(msg, self.addr)
            except Exception as e:
                print(f"Error sending BYE: {e}")

    def send_msg(self, display_name: str, content: str):
        protocol_type = "UDP" if self.protocol == "udp" else "TCP"

        if self.binary_mode and self.protocol == "udp":
            msg_id = self.server.get_next_msg_id()
            payload = display_name.encode('utf-8') + b'\x00' + content.encode('utf-8') + b'\x00'
            self.server.send_udp_binary_message(self, MSG_TYPE_MSG, msg_id, payload)
        else:
            msg = f"MSG FROM {display_name} IS {content}\r\n".encode()
            try:
                if self.protocol == "tcp":
                    self.skt.send(msg)
                else:
                    self.server.udp_socket.sendto(msg, self.addr)
            except Exception as e:
                print(f"Error sending message: {e}")
                self.close()


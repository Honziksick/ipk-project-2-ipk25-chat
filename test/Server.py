class Server:
    def __init__(self, host: str, port: int):
        self.tcp_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.tcp_socket.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.tcp_socket.bind((host, port))
        self.tcp_socket.listen()

        self.udp_socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.udp_socket.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.udp_socket.bind((host, port))

        self.clients = []
        self.udp_clients = {}
        self.udp_pending_messages = {}
        self.def_channel = "default"
        self.channels = [self.def_channel]
        self.queue = queue.Queue()
        self.running = True
        self.next_msg_id = 1

        self.msgproc = threading.Thread(target=self.__msg_proc_routine)
        self.msgproc.start()

        self.ping_thread = threading.Thread(target=self.__ping_routine)
        self.ping_thread.daemon = True
        self.ping_thread.start()

    def get_msg_type_name(self, msg_type_byte):
        return MSG_TYPE_NAMES.get(msg_type_byte, f"UNKNOWN({msg_type_byte:02X})")


    def get_next_msg_id(self):
        msg_id = self.next_msg_id
        self.next_msg_id = (self.next_msg_id + 1) % 65536
        return msg_id

    def track_udp_message(self, client_addr, msg_id, msg_type):
        if client_addr not in self.udp_pending_messages:
            self.udp_pending_messages[client_addr] = {}

        self.udp_pending_messages[client_addr][msg_id] = {
                'sent_time': time.time(),
                'msg_type': msg_type,
                'responded': False
                }

    def parse_binary_message(self, data):
        if len(data) < 3:
            return None, None, None

        msg_type = data[0]

        msg_id = struct.unpack('!H', data[1:3])[0]

        if msg_type == MSG_TYPE_AUTH:
            fields = data[3:].split(b'\x00')
            if len(fields) >= 3:
                username = fields[0].decode('utf-8')
                display_name = fields[1].decode('utf-8')
                secret = fields[2].decode('utf-8')
                return "AUTH", msg_id, (username, display_name, secret)

        elif msg_type == MSG_TYPE_JOIN:
            fields = data[3:].split(b'\x00')
            if len(fields) >= 2:
                channel_id = fields[0].decode('utf-8')
                display_name = fields[1].decode('utf-8') if len(fields) > 1 else ""
                return "JOIN", msg_id, (channel_id, display_name)

        elif msg_type == MSG_TYPE_MSG:
            fields = data[3:].split(b'\x00')
            if len(fields) >= 2:
                display_name = fields[0].decode('utf-8')
                content = fields[1].decode('utf-8')
                return "MSG", msg_id, (display_name, content)

        elif msg_type == MSG_TYPE_BYE:
            fields = data[3:].split(b'\x00')
            if len(fields) >= 1:
                display_name = fields[0].decode('utf-8')
                return "BYE", msg_id, (display_name,)

        elif msg_type == MSG_TYPE_ERR:
            fields = data[3:].split(b'\x00')
            if len(fields) >= 2:
                display_name = fields[0].decode('utf-8')
                content = fields[1].decode('utf-8')
                return "ERR", msg_id, (display_name, content)

        elif msg_type == MSG_TYPE_PING:
            return "PING", msg_id, ()

        elif msg_type == MSG_TYPE_CONFIRM:
            ref_msg_id = struct.unpack('!H', data[1:3])[0]
            return "CONFIRM", ref_msg_id, ()

        return None, None, None

    def send_ping(self, client):
        if not client.active or client.protocol != "udp":
            return False

        msg_id = self.get_next_msg_id()
        return self.send_udp_binary_message(client, MSG_TYPE_PING, msg_id)

    def send_udp_binary_message(self, client, msg_type_byte, msg_id, payload=b''):
        if not client.active or client.protocol != "udp":
            return False

        protocol_type = "UDP"

        if msg_type_byte == MSG_TYPE_PING:
            print(f"SEND ({protocol_type}, '{client.addr[0]}', {client.addr[1]}): PING {msg_id}")

        binary_msg = struct.pack('!BH', msg_type_byte, msg_id) + payload

        try:
            if msg_type_byte != MSG_TYPE_CONFIRM:
                self.track_udp_message(client.addr, msg_id, msg_type_byte)

            self.udp_socket.sendto(binary_msg, client.addr)
            return True
        except Exception as e:
            print(f"Error sending UDP message: {e}")
            return False

    def send_confirm(self, client, msg_id):
        protocol_type = "UDP" if client.protocol == "udp" else "TCP"

        if client.binary_mode and client.protocol == "udp":
            self.send_udp_binary_message(client, MSG_TYPE_CONFIRM, msg_id)
            print(f"SEND ({protocol_type}, '{client.addr[0]}', {client.addr[1]}): CONFIRM {msg_id} ({msg_id:04X})")
        else:
            pass

    def __ping_routine(self):
        PING_INTERVAL = 60.0
        MESSAGE_TIMEOUT = 5.0

        while self.running:
            time.sleep(PING_INTERVAL)
            current_time = time.time()

            for client in [c for c in self.clients if c.protocol == "udp" and c.active]:
                self.send_ping(client)

            for addr in list(self.udp_pending_messages.keys()):
                messages = list(self.udp_pending_messages[addr].items())

                for msg_id, info in messages:
                    if not info['responded'] and (current_time - info['sent_time']) > MESSAGE_TIMEOUT:
                        if addr in self.udp_clients:
                            client = self.udp_clients[addr]
                            print(f"UDP client {addr} did not respond to message ID {msg_id}, disconnecting")
                            client.send_bye("Server")
                            client.close()

                            if addr in self.udp_pending_messages:
                                del self.udp_pending_messages[addr]
                            break

                    elif info['responded'] and (current_time - info['sent_time']) > MESSAGE_TIMEOUT:
                        del self.udp_pending_messages[addr][msg_id]

                if addr in self.udp_pending_messages and not self.udp_pending_messages[addr]:
                    del self.udp_pending_messages[addr]

    def handle_binary_message(self, client, msg_type, msg_id, args):
        client.last_msg_id = msg_id
        result = False

        if msg_type == "AUTH":
            if len(args) == 3:
                username, display_name, secret = args
                handle_auth(self, client, username, display_name, secret)
                result = True

        elif msg_type == "JOIN":
            if len(args) >= 1:
                channel_id = args[0]
                display_name = args[1] if len(args) > 1 else client.display_name
                handle_join(self, client, channel_id, display_name)
                result = True

        elif msg_type == "MSG":
            if len(args) == 2:
                display_name, content = args
                handle_msg(self, client, display_name, content)
                result = True

        elif msg_type == "BYE":
            if len(args) == 1:
                display_name = args[0]
                handle_bye(self, client, display_name)
                result = True

        elif msg_type == "ERR":
            if len(args) == 2:
                display_name, content = args
                handle_err(self, client, display_name, content)
                result = True

        elif msg_type == "PING":
            protocol_type = "UDP" if client.protocol == "udp" else "TCP"
            print(f"PING ({protocol_type}, '{client.addr[0]}', {client.addr[1]}): PING {msg_id}")
            result = True

        elif msg_type == "CONFIRM":
            if client.addr in self.udp_pending_messages and msg_id in self.udp_pending_messages[client.addr]:
                self.udp_pending_messages[client.addr][msg_id]['responded'] = True
                msg_type_byte = self.udp_pending_messages[client.addr][msg_id]['msg_type']
                msg_type_name = self.get_msg_type_name(msg_type_byte)
                protocol_type = "UDP"
                print(f"CONFIRM ({protocol_type}, '{client.addr[0]}', {client.addr[1]}): {msg_type_name} {msg_id} ({msg_id:04X}) confirmed")
            else:
                print(f"UNMATCHED CONFIRM from {client.addr[0]}:{client.addr[1]}: {msg_id} ({msg_id:04X})")
                if client.addr in self.udp_pending_messages:
                    print(f"Pending messages for this client: {list(self.udp_pending_messages[client.addr].keys())}")
            result = True

        return result

    def start(self):
        inputs = [self.tcp_socket, self.udp_socket]

        while self.running:
            try:
                readable, _, _ = select.select(inputs, [], [], 1.0)

                for sock in readable:
                    if sock is self.tcp_socket:
                        client_socket, client_address = self.tcp_socket.accept()
                        print(f"CONNECTION (TCP, '{client_address[0]}', {client_address[1]}): New client connected")
                        client = Client(self, "tcp", client_socket, self.def_channel)
                        self.clients.append(client)

                    elif sock is self.udp_socket:
                        data, addr = self.udp_socket.recvfrom(60200)

                        if addr not in self.udp_clients:
                            print(f"CONNECTION (UDP, '{addr[0]}', {addr[1]}): New client connected")
                            client = Client(self, "udp", addr, self.def_channel)
                            self.clients.append(client)
                            self.udp_clients[addr] = client

                        client = self.udp_clients[addr]
                        msg_type, msg_id, args = self.parse_binary_message(data)
                        if msg_type:
                            client.binary_mode = True

                            if msg_type != "CONFIRM":
                                self.send_confirm(client, msg_id)

                            self.handle_binary_message(client, msg_type, msg_id, args)
                        else:
                            try:
                                text_message = data.decode('ascii')
                                self.handle_msg(client, text_message)
                            except Exception as e:
                                print(f"UNRECOGNIZED (UDP, '{addr[0]}', {addr[1]}): {data}")

            except Exception as e:
                print(f"Server error: {e}")
                break

    def stop(self):
        print("Stopping server...")
        self.running = False

        for client in list(self.clients):
            try:
                client.send_bye("Server")
            except Exception as e:
                print(f"Error sending BYE message to client {client.addr}: {e}")
            finally:
                client.close()

        self.tcp_socket.close()
        self.udp_socket.close()

    def handle_msg(self, sender, msg: str):
        self.queue.put((sender, msg))

    def __proc_msg(self, sender, msg: str):
        for name, pattern in patterns.items():
            match = pattern.match(msg)
            if match:
                handlers[name](self, sender, *match.groups())
                return
        protocol_type = "UDP" if sender.protocol == "udp" else "TCP"
        print(f"UNRECOGNIZED ({protocol_type}, '{sender.addr[0]}', {sender.addr[1]}): {msg}")

    def __msg_proc_routine(self):
        while self.running:
            try:
                sender, message = self.queue.get(timeout=1.0)
                self.__proc_msg(sender, message)
            except queue.Empty:
                continue
            except Exception as e:
                print(f"Error processing message: {e}")

